# -*- coding: utf-8 -*-
"""
Generates supabase/migrations/PENDING_0122_ramtha_option_lists.sql from lists.py.

Run from the repository root:  python supabase/ramtha/gen_0122.py
Writes LF only (newline=''), per CLAUDE.md rule 5.
"""
import io, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from lists import L

def q(s):
    return "'" + s.replace("'", "''") + "'"

out = []
out.append("""-- ═══════════════════════════════════════════════════════════════════════════
--  0122 — Ramtha's option lists: one ref_rmth_* table per response list
--
--  Every response-option list in RMTH_indicator_forms.xlsx, one table each,
--  English labels VERBATIM from the sheet in the sheet's order. 106 lists,
--  613 options. Generated from supabase/ramtha/lists.py, which is the
--  catalogue the form definitions are checked against; do not edit this file
--  by hand.
--
--  ── WHY 106 TABLES AND NOT ONE ──
--
--  The same reason 0002 and 0075 made one table per list for Sahel Horan:
--  a single-select column gets a real foreign key into the list it is allowed
--  to hold, and the application's ref-table machinery (useRefTable,
--  refLabel, the "Other (specify)" companion column) reads any table of this
--  shape unchanged. A generic option table keyed by list code would need a
--  trigger to do what a foreign key does, on every column, forever.
--
--  ── WHAT IS SHARED AND WHAT IS NOT ──
--
--  Seven lists are used by more than one sheet and exist once (nationality,
--  vulnerability, reached, project_type, sector, assessment_result,
--  modality_ipob). They were compared option for option before being merged:
--  two lists share a table only when every option matches. Where a sheet's
--  list differs from a Sahel Horan list by even one option it is a new table
--  here -- Ramtha's nationality list is "Jordanian / Syrian / Other
--  nationality (specify)", not ref_nationality's four -- and where two Ramtha
--  sheets differ by one option they are two tables (c11_sector adds
--  "Administrative and office skills"; f02_module adds "Digital tools for
--  small business"; b12_submitter_type adds "Academic institution").
--
--  ── ARABIC ──
--
--  The workbook has no Arabic for the forms. The labels here were drafted for
--  this platform under OQ-32's rule -- a plain phrase can be drafted, a named
--  regulatory artefact cannot -- and OQ-46 lists them for the Municipality's
--  review, naming the evidence-list rows that name documents. They are
--  drafted rather than left null because a Ramtha enumerator reading a form
--  in Arabic with 613 English options is not using a bilingual form.
--
--  Like every other ref_ table: RLS on, read by every signed-in role, written
--  by a coordinator, the four standard triggers, no hard delete. Shared
--  between municipalities, as all ref_ tables are (09 Part 1).
-- ═══════════════════════════════════════════════════════════════════════════

do $outer$
declare t text;
begin
  foreach t in array array[
""")
names = ["ref_rmth_" + k for k in L]
out.append(",\n".join("    " + q(n) for n in names))
out.append("""
  ] loop
    execute format($f$
      create table public.%I (
        id               uuid primary key default gen_random_uuid(),
        code             text not null unique,
        label_en         text not null,
        label_ar         text not null,
        sort_order       int  not null default 0,
        is_active        boolean not null default true,
        allows_free_text boolean not null default false,
        created_at       timestamptz not null default now(),
        updated_at       timestamptz not null default now(),
        created_by       uuid references auth.users(id),
        deleted_at       timestamptz
      )$f$, t);

    perform public.attach_standard_triggers(t);

    execute format('alter table public.%I enable row level security', t);
    execute format($f$create policy ref_read on public.%I
      for select to authenticated using (true)$f$, t);
    execute format($f$create policy ref_write on public.%I
      for all to authenticated
      using (public.is_coordinator())
      with check (public.is_coordinator())$f$, t);
  end loop;
end $outer$;

""")
for key, v in L.items():
    tbl = "ref_rmth_" + key
    out.append(f"-- ── {tbl} ({', '.join(v['used_by'])}) ──\n")
    out.append(f"insert into public.{tbl} (code, label_en, label_ar, sort_order, allows_free_text) values\n")
    rows = []
    for i, (code, en, ar, free) in enumerate(v['options'], 1):
        rows.append(f"  ({q(code)}, {q(en)}, {q(ar)}, {i}, {'true' if free else 'false'})")
    out.append(",\n".join(rows) + ";\n\n")

n_lists = len(L)
n_opts = sum(len(v['options']) for v in L.values())
out.append(f"""-- ── verification ──────────────────────────────────────────────────────────
do $verify$
declare
  v_tables int;
  v_rows   int;
  v_bad    int;
begin
  select count(*) into v_tables from pg_tables where schemaname = 'public' and tablename like 'ref\\_rmth\\_%';
  if v_tables <> {n_lists} then
    raise exception '0122: expected {n_lists} ref_rmth_ tables, found %', v_tables;
  end if;

  -- every table has RLS, two policies, the four triggers, and rows in it
  select count(*) into v_bad
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relname like 'ref\\_rmth\\_%' and c.relkind = 'r'
     and (not c.relrowsecurity
          or (select count(*) from pg_policy p where p.polrelid = c.oid) <> 2
          or (select count(*) from pg_trigger tg where tg.tgrelid = c.oid and not tg.tgisinternal) <> 4);
  if v_bad <> 0 then
    raise exception '0122: % ref_rmth_ tables are missing RLS, a policy or a trigger', v_bad;
  end if;

  execute (
    select 'select ' || string_agg(format('(select count(*) from public.%I)', tablename), ' + ')
      from pg_tables where schemaname = 'public' and tablename like 'ref\\_rmth\\_%')
    into v_rows;
  if v_rows <> {n_opts} then
    raise exception '0122: expected {n_opts} option rows, found %', v_rows;
  end if;

  -- and the shape the application relies on: every "(specify)" row allows
  -- free text, so its companion column is asked for
  execute (
    select 'select coalesce(sum(n), 0) from (' || string_agg(format(
      'select count(*) as n from public.%I where (label_en ilike ''%%(specify%%'' and not allows_free_text)', tablename), ' union all ') || ') s'
      from pg_tables where schemaname = 'public' and tablename like 'ref\\_rmth\\_%')
    into v_bad;
  if v_bad <> 0 then
    raise exception '0122: % "(specify)" options do not allow free text', v_bad;
  end if;
end $verify$;
""")
path = os.path.join(os.path.dirname(__file__), '..', 'migrations', 'PENDING_0122_ramtha_option_lists.sql')
io.open(path, 'w', encoding='utf-8', newline='').write("".join(out))
print('wrote', os.path.normpath(path), n_lists, 'lists', n_opts, 'options')
