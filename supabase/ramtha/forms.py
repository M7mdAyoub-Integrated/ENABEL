def form(fid, sheet, indicator, table, title_ar, calc_ar, who_ar, when_ar, fixed=None, filter_=None, sections=()):
    assert fid not in FORMS
    FORMS[fid] = dict(id=fid, sheet=sheet, indicator=indicator, table=table, title_ar=title_ar,
                      calc_ar=calc_ar, who_ar=who_ar, when_ar=when_ar,
                      fixed=fixed or {}, filter=filter_ or {}, sections=list(sections))

def sec(row, title_ar, *fields):
    return dict(row=row, title_ar=title_ar, fields=list(fields))

def fld(row, key, type_, label_ar, help_ar=None, **cfg):
    d = dict(row=row, key=key, type=type_, label_ar=label_ar, help_ar=help_ar)
    d.update(cfg)
    return d

# ── shared identification blocks ─────────────────────────────────────────
def ident_full(with_confirm=True, confirm_note=False, nid_note_ar=None):
    fs = [fld('National ID', 'national_id', 'nid', 'الرقم الوطني', nid_note_ar, required=True)]
    if with_confirm:
        fs.append(fld('National ID (validation - re-enter)', 'national_id_confirm', 'nid_confirm',
                      'الرقم الوطني (للتحقق - أعد الإدخال)', 'يجب أن يطابق الحقل أعلاه.' if confirm_note else None, required=True))
    fs.append(fld('Full name', 'full_name', 'person_name', 'الاسم الكامل', required=True))
    return fs

