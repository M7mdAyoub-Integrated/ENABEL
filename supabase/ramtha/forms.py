"""
The seventeen Ramtha forms, field by field, from RMTH_indicator_forms.xlsx.

This is the catalogue that gen_forms.py turns into
  app/src/rmth/forms.generated.ts        the definitions the screens render
  app/src/locales/en/rmth.json           English: every label VERBATIM from the sheet
  app/src/locales/ar/rmth.json           Arabic: drafted here (the workbook has none)

Every `row` below names a field label exactly as the sheet has it; the generator
looks it up in the sheet and FAILS if it is not there, so a label cannot drift
from the workbook. The enumerator's note (column 3) is pulled from the sheet as
the field's help text; where a row has a note, `help_ar` is required here.

Field types (what the screen renders and what the save payload carries):
  nid          national ID -> person.national_id          nid_confirm  re-entry, must match
  person_name  -> person.full_name (locked when on file)  person_phone -> person.phone
  person_sex   -> person.sex (Male / Female, verbatim)    age          -> column age_years (+ person)
  text / area / number / date / month / phone             plain columns
  select       one ref_rmth_* list (+ `other` column)     multi        one option-junction question (+ other)
  bool         a two-option decision on a boolean column  choice       a fixed text/int column with listed values
  record       a picker over another Ramtha table         records      several (a junction payload)
  parts        several columns under one sheet row        grid         B1's support-criticality grid
  services     E0.1's live services with dates            readonly     assigned or derived by the database
"""

