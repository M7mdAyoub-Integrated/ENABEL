def framework_sql():
    lines = []
    for code, view, table in VIEWS:
        lines.append("update public.indicator i set formula = %s, data_source = %s, view_name = %s\n"
                     "  from public.municipality m where m.id = i.municipality_id and m.code = 'KHLD' and i.code = %s;"
                     % (q(formula(code)), q(table), q(view), q(code)))
    lines.append("-- SO2-C2's statement is the reviewed framework sheet's")
    lines.append("update public.indicator i set name_en = %s\n"
                 "  from public.municipality m where m.id = i.municipality_id and m.code = 'KHLD' and i.code = 'C2';"
                 % q(framework_name('C2')))
    return '\n'.join(lines)


