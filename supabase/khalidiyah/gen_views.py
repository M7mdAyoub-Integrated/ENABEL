def formula(code):
    return CALC[full(code)]['formula']


def framework_name(code):
    for r in FRAME:
        if r and r[0] == full(code):
            return r[2]
    raise KeyError(code)


def sheet(code):
    """The sheet's formula and frequency as an SQL comment block."""
    c = CALC[full(code)]
    out = []
    for label, text in (('formula', c['formula']), ('frequency', c['frequency'])):
        lines, cur, first = [], '--    %s: "' % label, True
        for w in text.split():
            if len(cur) + len(w) + 1 > 78:
                lines.append(cur)
                cur, first = '--      ', True
            cur += ('' if first else ' ') + w
            first = False
        lines.append(cur + '"')
        out += lines
    return '\n'.join(out)


