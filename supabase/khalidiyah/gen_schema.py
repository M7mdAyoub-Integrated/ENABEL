def col_line(name, sqltype, notnull, ref):
    tail = ''
    if ref == '@person':
        tail = ' references public.person(id)'
    elif ref == 'now()':
        tail = ' default now()'
    elif ref == 'default false':
        tail = ' default false'
    elif ref and not ref.startswith('@'):
        tail = ' references public.ref_khld_%s(id)' % ref
    return '  %s %s%s%s,' % (name, sqltype, ' not null' if notnull else '', tail)


