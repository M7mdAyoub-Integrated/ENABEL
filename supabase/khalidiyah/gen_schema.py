        text = fn()
        applied = [p for p in glob.glob(os.path.join(ROOT, 'supabase', 'migrations', '*_%s_%s.sql' % (nnnn, name)))
                   if not os.path.basename(p).startswith('PENDING_')]
        if applied:
            same = open(applied[0], encoding='utf-8', newline='').read() == text
            print('%s applied as %s: %s' % (nnnn, os.path.basename(applied[0]), 'reproduced byte for byte' if same else 'DIFFERS'))
